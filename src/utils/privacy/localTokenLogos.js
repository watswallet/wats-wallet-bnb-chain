const keyOf = (chainId, address) => {
    if (typeof address !== 'string') return null
    const id = Number(chainId)
    return Number.isInteger(id) ? id + ':' + address.toLowerCase() : null
}

/** (chainId, adres) paketlenmis bir yerel logoya sahip mi? */
export const hasLocalTokenLogo = (chainId, address) => {
    const k = keyOf(chainId, address)
    return k !== null && LOCAL_TOKEN_LOGOS.has(k)
}

/** Yerel logo yolu ya da yoksa null. */
export const localTokenLogoPath = (chainId, address) => {
    const k = keyOf(chainId, address)
    return k !== null && LOCAL_TOKEN_LOGOS.has(k) ? '/tokens/' + k.replace(':', '/') + '.png' : null
}
